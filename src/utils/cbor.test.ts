import { describe, expect, test } from "bun:test";
import { cborDecode } from "./cbor.js";

describe("cborDecode()", () => {
  test.each(
    [
      [],
      [0xbf],
      [0x9f],
      [0x5f],
      [0x7f],
      [0xbf, 0x01],
      [0xa1, 0x01],
      [0x81],
      [0x18],
      [0x19, 0x00],
      [0x1a, 0x00],
      [0x1b, 0x00],
      [0xfa, 0x00],
      [0xfb, 0x00],
      [0x41],
      [0x61],
      [0x61, 0xc2, 0xa2],
      [0x7f, 0x61, 0xc2, 0xa2, 0xff],
      [0x9b, 0x00, 0x20, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
    ].map((bytes) => ({ bytes }))
  )("rejects truncated input %j", ({ bytes }) => {
    expect(() => cborDecode(Uint8Array.from(bytes).buffer)).toThrow();
  });

  test.each([
    [[0x5f, 0x40, 0x42, 0x01, 0x02, 0xff], Uint8Array.from([1, 2])],
    [[0x7f, 0x60, 0x61, 0x61, 0x62, 0xc2, 0xa2, 0xff], "a¢"],
    [[0x9f, 0x01, 0x02, 0xff], [1, 2]],
    [[0xbf, 0x61, 0x61, 0x01, 0xff], { a: 1 }],
  ])("decodes valid indefinite input %j", (bytes, value) => {
    expect(cborDecode(Uint8Array.from(bytes as number[]).buffer)).toEqual(value);
  });

  test("preserves definite ABI arrays", () => {
    expect(cborDecode(Uint8Array.from([0x81, 0xa0]).buffer)).toEqual([{}]);
  });
});
